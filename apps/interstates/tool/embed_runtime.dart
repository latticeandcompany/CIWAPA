// Regenerates lib/src/runtime_sources.g.dart from the host runtimes and the library block. Run
// from the package:
//   dart run tool/embed_runtime.dart
import 'dart:io';

void main() => File('lib/src/runtime_sources.g.dart').writeAsStringSync(
  embed(
    hostDart: File('lib/runtime/ioi_host.dart').readAsStringSync(),
    hostC: File('runtime/host.c').readAsStringSync(),
    library: File('runtime/interstates.xc').readAsStringSync(),
  ),
);

/// The Dart host is copied next to the program and runtime.dart, so its import of the runtime
/// becomes a relative one.
String embed({
  required String hostDart,
  required String hostC,
  required String library,
}) {
  const package = "import 'package:ciwapa_dart/runtime/runtime.dart';";
  if (!hostDart.contains(package)) {
    throw StateError('ioi_host.dart: no $package');
  }
  final sources = {
    'ioiHostDart': hostDart.replaceFirst(package, "import 'runtime.dart';"),
    'ioiHostC': hostC,
    'interstatesLibrary': library,
  };
  final out = StringBuffer(
    '// Generated by tool/embed_runtime.dart from lib/runtime, runtime/host.c and\n'
    '// runtime/interstates.xc. Do not edit.\n',
  );
  for (final MapEntry(:key, :value) in sources.entries) {
    if (value.contains("'''")) throw StateError("$key can't contain '''");
    out.write("const $key = r'''\n$value''';\n");
  }
  return out.toString();
}
