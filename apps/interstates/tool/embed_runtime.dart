// Regenerates lib/src/runtime_sources.g.dart from the host runtimes, ActiveCassette's adapter
// sources and the library block. Run from the package:
//   dart run tool/embed_runtime.dart
import 'dart:io';

void main() => File('lib/src/runtime_sources.g.dart').writeAsStringSync(
  embed(
    hostDart: File('lib/runtime/ioi_host.dart').readAsStringSync(),
    hostC: File('runtime/host.c').readAsStringSync(),
    adapterHeader: File('runtime/ioi_adapter.h').readAsStringSync(),
    sqliteAdapter: File('runtime/sqlite_adapter.c').readAsStringSync(),
    activecassette: File('runtime/activecassette.c').readAsStringSync(),
    library: File('runtime/interstates.xc').readAsStringSync(),
  ),
);

/// The Dart host is copied next to the program and runtime.dart, so its import of the runtime
/// becomes a relative one; host.c is copied alone, so the adapter header goes inside it.
String embed({
  required String hostDart,
  required String hostC,
  required String adapterHeader,
  required String sqliteAdapter,
  required String activecassette,
  required String library,
}) {
  const package = "import 'package:ciwapa_dart/runtime/runtime.dart';";
  if (!hostDart.contains(package)) {
    throw StateError('ioi_host.dart: no $package');
  }
  const include = '#include "ioi_adapter.h"\n';
  if (!hostC.contains(include)) throw StateError('host.c: no $include');
  final sources = {
    'ioiHostDart': hostDart.replaceFirst(package, "import 'runtime.dart';"),
    'ioiHostC': hostC.replaceFirst(include, adapterHeader),
    'ioiAdapterHeader': adapterHeader,
    'sqliteAdapterC': sqliteAdapter,
    'activecassetteC': activecassette,
    'interstatesLibrary': library,
  };
  final out = StringBuffer(
    '// Generated by tool/embed_runtime.dart from lib/runtime, runtime/ and\n'
    '// runtime/interstates.xc. Do not edit.\n',
  );
  for (final MapEntry(:key, :value) in sources.entries) {
    if (value.contains("'''")) throw StateError("$key can't contain '''");
    out.write("const $key = r'''\n$value''';\n");
  }
  return out.toString();
}
