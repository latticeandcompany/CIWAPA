// Regenerates lib/src/runtime_source.g.dart from lib/runtime/runtime.dart. Run from the package:
//   dart run tool/embed_runtime.dart
import 'dart:io';

void main() => File(
  'lib/src/runtime_source.g.dart',
).writeAsStringSync(embed(File('lib/runtime/runtime.dart').readAsStringSync()));

String embed(String runtime) {
  if (runtime.contains("'''")) {
    throw StateError("runtime.dart can't contain '''");
  }
  return "// Generated by tool/embed_runtime.dart from lib/runtime/runtime.dart. Do not edit.\n"
      "const runtimeSource = r'''\n$runtime''';\n";
}
