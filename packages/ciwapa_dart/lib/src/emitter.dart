import 'package:ciwapa_core/ciwapa_core.dart';

/// Generates the Dart program for an [IrProgram].
///
/// Control flow is a `switch` on `pc` inside a loop, but only where control can arrive from
/// elsewhere: a statement in [_entries], or a NEXT's return point, where a RESUME lands. Those get
/// consecutive case numbers from 2 ([entry], [after]), so the switches compile as jump tables.
/// In between, statements run straight on, one after another. pc 1 is falling off the end of the
/// program (E633).
///
/// The statements are split into chunk functions of [chunkSize], because the Dart AOT compiler
/// fails on a single function with tens of thousands of cases. Each chunk loops on its own and
/// returns pc to `_run` once control leaves it. A jump within a chunk is a `continue` to the
/// target's labeled case, which skips the dispatch.
class DartEmitter {
  DartEmitter(this.program, this.options);

  final IrProgram program;
  final EmitOptions options;
  var _out = StringBuffer();
  var _chunk = 0;
  late final _library = options.optimize
      ? findNativeLibraryCalls(program)
      : const <int, NativeLibraryCall>{};
  late final _natives = options.optimize
      ? findNativeCalls(program)
      : const <int, NativeCall>{};

  /// The statements to emit: the ones a run can reach. Libraries appended to a program can be
  /// much bigger than the part it uses, and `dart compile exe` takes time over every statement.
  late final Set<int> _reachable = reachable(program);

  bool _emitted(int ordinal) => _reachable.contains(ordinal);

  /// The statements control reaches other than by running on from the one before: the first,
  /// NEXT targets, COME FROMs (their traps jump there), and the first of every chunk.
  late final Set<int> _entries = {
    1,
    for (var o = 1; o <= program.statements.length; o += chunkSize) o,
    for (final s in program.statements) ...[
      if (s.op case IrNext(:final target) when target != 0) target,
      ?s.comeFrom,
    ],
  }.where(_emitted).toSet();

  late final (Map<int, int>, Map<int, int>, List<int>, int) _numbers = () {
    final entries = <int, int>{}, afters = <int, int>{}, chunkStarts = <int>[];
    var next = 2;
    for (final s in program.statements) {
      if ((s.ordinal - 1) % chunkSize == 0) chunkStarts.add(next);
      if (!_emitted(s.ordinal)) continue;
      if (_entries.contains(s.ordinal)) entries[s.ordinal] = next++;
      if (s.op is IrNext) afters[s.ordinal] = next++;
    }
    return (entries, afters, chunkStarts, next - 1);
  }();

  /// The case number of [ordinal]'s entry.
  int entry(int ordinal) => _numbers.$1[ordinal]!;

  /// The case number of the NEXT [ordinal]'s return point.
  int after(int ordinal) => _numbers.$2[ordinal]!;

  static const fellOff = 1;
  static const chunkSize = 1024;

  String _jump(int pc) {
    final starts = _numbers.$3;
    final inChunk =
        pc >= starts[_chunk] &&
        (_chunk + 1 == starts.length || pc < starts[_chunk + 1]);
    return inChunk ? 'continue c$pc;' : 'pc = $pc; break;';
  }

  String _case(int pc) => 'c$pc: case $pc:';

  String emit() {
    _out
      ..writeln(
        '// Generated by ciwapa-dart from ${options.sourceName}. Do not edit.',
      )
      ..writeln("import 'dart:typed_data';")
      ..writeln()
      ..writeln("import 'runtime.dart';")
      ..writeln()
      ..writeln('final _v = Uint32List(${program.scalars.length});')
      ..writeln('final _ig = Uint8List(${program.scalars.length});')
      ..write(
        program.extracal
            ? 'final _w = Uint64List(${program.wideScalars.length});\n'
                  'final _igw = Uint8List(${program.wideScalars.length});\n'
            : '',
      )
      ..writeln('final _ab = Uint8List(${program.statements.length + 1});')
      ..writeln('final _abT = Int64List(${program.statements.length + 1});')
      ..writeln('final _ger = Uint8List(${Gerund.values.length});')
      ..writeln('final _gerT = Int64List(${Gerund.values.length});')
      ..writeln('var _clock = 0;')
      ..writeln()
      ..writeln('void main(List<String> args) {')
      ..writeln(
        '  ickInit(args, base: ${program.base}, clockface: ${options.clockface}, '
        'arrayCount: ${program.arrays.length}, values: _v, ignored: _ig, messages: _messages'
        '${program.extracal ? ', wideValues: _w, wideIgnored: _igw, wideArrayCount: ${program.wideArrays.length}, latin: true, extracal: true' : ''});',
      );
    if (program.engine) {
      _emitEngine();
    } else {
      _emitStraight();
    }
    for (final MapEntry(key: mask, value: name) in _selectFunctions64.entries) {
      final parts = [
        for (final run in selectRuns(mask, bits: 64))
          '((x >>> ${run.from}) & ${_literal(run.width == 64 ? -1 : (1 << run.width) - 1)}) << ${run.to}',
      ];
      _out
        ..writeln()
        ..writeln(
          'int $name(int x) => ${parts.isEmpty ? '0' : parts.join(' | ')};',
        );
    }
    for (final MapEntry(key: mask, value: name) in _selectFunctions.entries) {
      final steps = compressSteps(mask);
      if (steps.length < selectRuns(mask).length) {
        _out
          ..writeln()
          ..writeln('int $name(int x) {')
          ..writeln('  x &= $mask;');
        for (final step in steps) {
          _out
            ..writeln('  final moving${step.shift} = x & ${step.moving};')
            ..writeln(
              '  x = x ^ moving${step.shift} | moving${step.shift} >> ${step.shift};',
            );
        }
        _out
          ..writeln('  return x;')
          ..writeln('}');
        continue;
      }
      final parts = [
        for (final run in selectRuns(mask))
          '((x >> ${run.from}) & ${(1 << run.width) - 1}) << ${run.to}',
      ];
      _out
        ..writeln()
        ..writeln(
          'int $name(int x) => ${parts.isEmpty ? '0' : parts.join(' | ')};',
        );
    }
    if (_sharedGuard) {
      _out
        ..writeln()
        ..writeln("@pragma('vm:never-inline')")
        ..writeln('bool _unabstained(int ordinal, int gerund) =>')
        ..writeln(
          '    (_abT[ordinal] >= _gerT[gerund] ? _ab[ordinal] : _ger[gerund]) == 0;',
        );
    }
    _out
      ..writeln()
      ..writeln('const _messages = {');
    for (final m in IclError.all) {
      _out.writeln(
        '  ${m.code}: IckMessage(${_string(m.text)}, ${_string(m.joke)}),',
      );
    }
    _out.writeln('};');
    return _out.toString();
  }

  /// The program as straight-line code: every Mode 1 program, and EXTRACAL programs that use none
  /// of `ick`'s control extensions.
  void _emitStraight() {
    for (final s in program.statements) {
      if (s.initiallyAbstained) _out.writeln('  _ab[${s.ordinal}] = 1;');
    }
    final chunks = (program.statements.length + chunkSize - 1) ~/ chunkSize;
    _out
      ..writeln('  _run();')
      ..writeln('}')
      ..writeln()
      ..writeln('void _run() {')
      ..writeln(
        '  var pc = ${program.statements.isEmpty ? fellOff : entry(1)};',
      )
      ..writeln('  while (true) {')
      ..writeln(
        '    if (pc == $fellOff) ickFatal(633, ${program.userStatements + 1});',
      )
      ..writeln(
        '    if (pc < 2 || pc > ${_numbers.$4}) throw StateError("no statement at pc \$pc");',
      )
      ..writeln('    pc = switch (pc) {');
    final starts = _numbers.$3;
    for (var c = 0; c < chunks - 1; c++) {
      _out.writeln('      < ${starts[c + 1]} => _chunk$c(pc),');
    }
    _out
      ..writeln(
        chunks == 0
            ? '      _ => throw StateError("no statement at pc \$pc"),'
            : '      _ => _chunk${chunks - 1}(pc),',
      )
      ..writeln('    };')
      ..writeln('  }')
      ..writeln('}');
    for (var c = 0; c < chunks; c++) {
      _chunk = c;
      _out
        ..writeln()
        // Every index in a chunk is a constant inside its array, or an element offset that
        // ickElement already checked.
        ..writeln("@pragma('vm:unsafe:no-bounds-checks')")
        ..writeln('int _chunk$c(int pc) {')
        // Locals, because every access to a lazily initialized top-level checks it first.
        ..writeln(
          '  final v = _v, ig = _ig, ab = _ab, abT = _abT, ger = _ger, gerT = _gerT'
          '${program.extracal ? ', w = _w, igw = _igw' : ''};',
        )
        ..writeln('  while (true) {')
        ..writeln('    switch (pc) {');
      for (final s in program.statements.skip(c * chunkSize).take(chunkSize)) {
        if (!_emitted(s.ordinal)) continue;
        _out.writeln(
          _entries.contains(s.ordinal)
              ? '      ${_case(entry(s.ordinal))} // statement ${s.ordinal}'
              : '        // statement ${s.ordinal}',
        );
        _statement(s);
      }
      _out
        ..writeln('      default:')
        ..writeln('        return pc;')
        ..writeln('    }')
        ..writeln('  }')
        ..writeln('}');
    }
  }

  /// The program on EXTRACAL's control engine (R3): the engine runs the control flow from a table,
  /// and calls back into the compiled bodies of the other statements.
  void _emitEngine() {
    final table = EngineTable(program);
    if (program.overloading) {
      _out.writeln(
        '  ickInitOverloading(${program.scalars.length + program.wideScalars.length}, '
        '${program.overloads.length}, _ovGet, _ovSet);',
      );
    }
    _out
      ..writeln(
        '  ickXRun(XProgram(table: _xTable, lists: _xLists, texts: _xTexts, '
        'userStatements: ${program.userStatements}, body: _xBody, expr: _xExpr, native: _xNative'
        '${program.signatures.isEmpty ? '' : ', signatures: ${program.signatures.length}, unknown: _xUnknown'}));',
      )
      ..writeln('}')
      ..writeln()
      ..writeln('const _xTable = <int>[${table.rows.join(', ')}];')
      ..writeln('const _xLists = <int>[${table.lists.join(', ')}];')
      ..writeln('const _xTexts = <int, String>{');
    for (final MapEntry(:key, :value) in table.texts.entries) {
      _out.writeln('  $key: ${_string(value)},');
    }
    _out.writeln('};');

    final plain = [
      for (final s in program.statements)
        if (_plainBody(s.op)) s,
    ];
    final chunks = (plain.length + chunkSize - 1) ~/ chunkSize;
    _out
      ..writeln()
      ..writeln('void _xBody(int ordinal) {');
    for (var c = 0; c < chunks; c++) {
      final last =
          plain[(c + 1) * chunkSize - 1 < plain.length
              ? (c + 1) * chunkSize - 1
              : plain.length - 1];
      _out.writeln(
        '  if (ordinal <= ${last.ordinal}) return _xBody$c(ordinal);',
      );
    }
    _out.writeln('}');
    for (var c = 0; c < chunks; c++) {
      _out
        ..writeln()
        ..writeln("@pragma('vm:unsafe:no-bounds-checks')")
        ..writeln('void _xBody$c(int ordinal) {')
        ..writeln(
          '  final v = _v, ig = _ig${program.extracal ? ', w = _w, igw = _igw' : ''};',
        )
        ..writeln('  switch (ordinal) {');
      for (final s in plain.skip(c * chunkSize).take(chunkSize)) {
        _out.writeln('    case ${s.ordinal}:');
        _line('{');
        _body(s);
        _line('}');
      }
      _out
        ..writeln('  }')
        ..writeln('}');
    }

    _emitOverloads();
    _emitUnknowns();
    _out
      ..writeln()
      ..writeln('int _xExpr(int ordinal) {')
      ..writeln('  final v = _v${program.extracal ? ', w = _w' : ''};')
      ..writeln('  switch (ordinal) {');
    for (final s in program.statements) {
      if (s.op case IrForget(:final count) || IrResume(:final count)) {
        _out.writeln('    case ${s.ordinal}:');
        _line('return ${_count(count, s.next)};');
      }
      if (s.op case IrAbstain(count: final count?)) {
        _out.writeln('    case ${s.ordinal}:');
        _line('return ${_expr(count, s.next)};');
      }
      if (s.op
          case IrComputedComeFrom(:final label) ||
              IrCreate(target: final label?)) {
        _out.writeln('    case ${s.ordinal}:');
        _line('return ${_expr(label, s.next)};');
      }
    }
    _out
      ..writeln('  }')
      ..writeln('  return 0;')
      ..writeln('}')
      ..writeln()
      ..writeln('bool _xNative(int ordinal) {')
      ..writeln('  final v = _v, ig = _ig;')
      ..writeln('  switch (ordinal) {');
    for (final s in program.statements) {
      if (s.op case IrNext(:final target) when _library.containsKey(target)) {
        final native = _library[target]!;
        _out.writeln('    case ${s.ordinal}:');
        _line('if (${_libraryGuard(native, (o) => 'ickXClear($o)')}) {');
        _line('  ${_libraryCall(native)}');
        _line('  return true;');
        _line('}');
      }
      if (s.op case IrNext(:final target) when _natives.containsKey(target)) {
        final call = _natives[target]!;
        final guard = [
          'ickNextFree() >= ${call.depth}',
          for (final w in call.watched) 'ig[${w.index}] == 0',
          for (final o in call.abstainable) 'ickXClear($o)',
        ];
        final args = [for (final a in call.args) 'v[${a.index}]'];
        if (args.length == 1) args.add('0');
        _out.writeln('    case ${s.ordinal}:');
        _line('if (${guard.join(' && ')}) {');
        _line('  final r = ickSyslib(${call.label}, ${args.join(', ')});');
        _line('  if (r >= 0) {');
        _line('    v[${call.result.index}] = r;');
        if (call.flag case final flag?) {
          _line('    v[${flag.index}] = r >> 32 == 0 ? 1 : 2;');
        }
        _line('    return true;');
        _line('  }');
        _line('}');
      }
    }
    _out
      ..writeln('  }')
      ..writeln('  return false;')
      ..writeln('}');
  }

  /// What each unknown statement does when a CREATE has given it a meaning (R3): on the way in, it
  /// evaluates its operands, then stashes `:1601` and on and makes each stand for its operand; on
  /// the way back, it retrieves them. The stashing goes from the last operand to the first, as in
  /// `ick`.
  void _emitUnknowns() {
    if (program.signatures.isEmpty) return;
    _out
      ..writeln()
      ..writeln('void _xUnknown(int ordinal, bool entering) {')
      ..writeln(
        '  final v = _v, ig = _ig${program.extracal ? ', w = _w, igw = _igw' : ''};',
      )
      ..writeln('  switch (ordinal) {');
    for (final s in program.statements) {
      if (s.op case IrUnknown(:final operands, :final variables)) {
        _out.writeln('    case ${s.ordinal}:');
        _line('if (entering) {');
        // `ick` evaluates the operands, in order, before anything else.
        for (final id in operands) {
          final e = program.overloads[id - 1];
          if (e is! IrArrayItem) _line('  ${_expr(e, s.next)};');
        }
        for (var i = variables.length - 1; i >= 0; i--) {
          final v = variables[i];
          _line('  ickStashScalar(${v.index}, ${s.next});');
          _line('  ickOvStash(${_key(v)});');
          _line('  ickOvSlat(${_key(v)}, ${operands[i]}, 0);');
        }
        _line('} else {');
        for (var i = variables.length - 1; i >= 0; i--) {
          final v = variables[i];
          _line('  ickRetrieveScalar(${v.index}, ${s.next});');
          _line('  ickOvRetrieve(${_key(v)});');
        }
        _line('}');
      }
    }
    _out
      ..writeln('  }')
      ..writeln('}');
  }

  /// Each overload's expression, read and assigned to (R3). `next` is the reading or assigning
  /// statement's, which the runtime passes in.
  void _emitOverloads() {
    if (!program.overloading) return;
    final locals =
        '  final v = _v, ig = _ig${program.extracal ? ', w = _w, igw = _igw' : ''};';
    _out
      ..writeln()
      ..writeln('int _ovGet(int id, int next) {')
      ..writeln(locals)
      ..writeln('  switch (id) {');
    for (final (i, e) in program.overloads.indexed) {
      _out.writeln('    case ${i + 1}:');
      // A whole array that a created statement's `:1601` stands for has no value.
      _line(
        e is IrArrayItem
            ? 'ickFatal(277, next);'
            : 'return ${_expr(e, 'next')};',
      );
    }
    _out
      ..writeln('  }')
      ..writeln('  return 0;')
      ..writeln('}')
      ..writeln()
      ..writeln('void _ovSet(int id, int value, int next) {')
      ..writeln(locals)
      ..writeln('  switch (id) {');
    for (final (i, e) in program.overloads.indexed) {
      _out.writeln('    case ${i + 1}:');
      _line('{');
      _reverse(e, 'value');
      _line('}');
    }
    _out
      ..writeln('  }')
      ..writeln('}');
  }

  var _reverseTemps = 0;

  /// Assigns [target] to [e] backwards, as `ick` does for an overloaded variable: a mingle's
  /// operands get the target's odd and even bits, a select's left operand gets the target and its
  /// right operand all ones, a unary operator is undone, and a constant is E277. "All ones" is
  /// [width] bits: `ick` starts at 16 and takes each unary operator's width on the way down.
  void _reverse(IrExpr e, String target, [int width = 16]) {
    String temp(String value) {
      final name = 'r${_reverseTemps++}';
      _line('final $name = $value;');
      return name;
    }

    String fits(int to) =>
        to == 64 ? target : 'ickCheckNarrow($target, $to, next)';
    switch (e) {
      case IrScalar(:final slot):
        final store = slot.wide ? 'w' : 'v', flags = slot.wide ? 'igw' : 'ig';
        _line('if (!ickOvSet(${_key(slot)}, $target, next)) {');
        final value = temp(fits(slot.width));
        _line(
          'if ($flags[${slot.index}] == 0) $store[${slot.index}] = $value;',
        );
        _line('}');
      case IrSlat(:final slot, :final id):
        final store = slot.wide ? 'w' : 'v', flags = slot.wide ? 'igw' : 'ig';
        final value = temp(fits(slot.width));
        _line(
          'if ($flags[${slot.index}] == 0) $store[${slot.index}] = $value;',
        );
        _line('ickOvSlat(${_key(slot)}, $id, 0);');
      case IrElement(:final array, :final subscripts):
        final suffix = _suffix(array);
        final offset = temp(_element(array, subscripts, 'next'));
        final value = temp(fits(array.width));
        _line(
          'if (!ickArrayIgnored$suffix(${array.index})) ickArrayData$suffix(${array.index})[$offset] = $value;',
        );
      case IrMingle(:final left, :final right) when program.base == 2:
        final odd = temp('ickSelect64($target, 0xAAAAAAAAAAAAAAAA)');
        final even = temp('ickSelect64($target, 0x5555555555555555)');
        _reverseInto(left, odd, width);
        _reverseInto(right, even, width);
      case IrSelect(:final left, :final right) when program.base == 2:
        _reverseInto(left, target, width);
        _reverseInto(
          right,
          _literal(width == 64 ? -1 : (1 << width) - 1),
          width,
        );
      case IrUnary(:final op, :final operand) when program.base == 2:
        final undone = temp(
          'ickReverseUnary(${UnaryOp.values.indexOf(op)}, $target, ${operand.valueWidth}, next)',
        );
        _reverseInto(operand, undone, operand.valueWidth);
      default:
        // Constants can't change, and the other bases' operators can't be undone.
        _line('ickFatal(277, next);');
    }
  }

  void _reverseInto(IrExpr e, String target, int width) {
    _line('{');
    _reverse(e, target, width);
    _line('}');
  }

  /// The statements whose bodies are compiled for the control engine; it runs the rest itself.
  static bool _plainBody(IrOp op) => switch (op) {
    IrAssign() ||
    IrDimension() ||
    IrVarList() ||
    IrWriteIn() ||
    IrReadOut() ||
    IrPetition() => true,
    _ => false,
  };

  static String _string(String s) {
    final escaped = s
        .replaceAll(r'\', r'\\')
        .replaceAll("'", r"\'")
        .replaceAll(r'$', r'\$')
        .replaceAll('\n', r'\n')
        .replaceAll('\t', r'\t');
    return "'$escaped'";
  }

  void _line(String code) => _out.writeln('        $code');

  /// Gerunds some ABSTAIN or REINSTATE names. A statement with one of them is abstained by
  /// whichever was set last, its own flag or its gerund's, as the stamps from `_clock` tell; so a
  /// gerund ABSTAIN is one store, not one per statement.
  late final Set<Gerund> _gerunds = {
    for (final s in program.statements)
      if (s.op case IrAbstain(:final gerunds)) ...gerunds,
  };

  /// Whether the gerund guards call one shared function instead of comparing stamps inline. A
  /// call is slower to run, but past a few dozen inline guards are a large part of what
  /// `dart compile exe` spends on the program.
  late final bool _sharedGuard =
      program.statements
          .where(
            (s) =>
                _emitted(s.ordinal) &&
                s.abstainable &&
                _gerunds.contains(s.gerund),
          )
          .length >
      64;

  /// The condition that statement [ordinal] isn't abstained.
  String _clear(int ordinal) {
    final g = program.at(ordinal).gerund;
    if (g == null || !_gerunds.contains(g)) return 'ab[$ordinal] == 0';
    return _sharedGuard
        ? '_unabstained($ordinal, ${g.index})'
        : '(abT[$ordinal] >= gerT[${g.index}] ? ab[$ordinal] : ger[${g.index}]) == 0';
  }

  /// Where control goes after [s] when nothing jumps: on into the next statement, unless that
  /// one starts a new case. Running off the user's program is E633 at the user's last ordinal + 1
  /// (decision T37); running off the library, at its own.
  String? _fallthrough(IrStatement s) {
    if (s.ordinal == program.userStatements) return 'pc = $fellOff; break;';
    if (s.ordinal == program.statements.length) {
      return 'ickFatal(633, ${program.statements.length + 1});';
    }
    if (_entries.contains(s.ordinal + 1)) {
      return _jump(entry(s.ordinal + 1));
    }
    return null;
  }

  void _statement(IrStatement s) {
    if (s.bug) _line('ickFatal(774, ${s.next});');
    final guard = [
      if (s.op is! IrComeFrom) ...[
        if (s.percent case final percent? when percent < 100)
          'ickRoll($percent)',
        if (s.abstainable) _clear(s.ordinal),
      ],
    ];
    final outer = _out;
    _out = StringBuffer();
    if (s.faults.isNotEmpty && s.op is! IrComeFrom) {
      _line('ickFatal(${s.faults.first.code}, ${s.next});');
    } else {
      _body(s);
    }
    final body = '$_out';
    _out = outer;
    // A block only when the body is guarded or declares a local of its own.
    final block =
        guard.isNotEmpty ||
        body.contains(RegExp(r'^\s*final ', multiLine: true));
    if (block) _line(guard.isEmpty ? '{' : 'if (${guard.join(' && ')}) {');
    _out.write(body);
    if (block) _line('}');
    if (s.op is IrNext) {
      _line(_jump(after(s.ordinal)));
      _out.writeln('      ${_case(after(s.ordinal))}');
    }
    _trap(s);
    if (_fallthrough(s) case final next?) _line(next);
  }

  /// The COME FROM trap after [s]: jumps to the COME FROM aimed at it when that COME FROM's own
  /// guard passes. A COME FROM's own faults fire in place of its jump (decision L2).
  void _trap(IrStatement s) {
    final comeFrom = s.comeFrom;
    if (comeFrom == null) return;
    final c = program.at(comeFrom);
    final guard = [
      if (c.percent != null && c.percent! < 100) 'ickRoll(${c.percent})',
      if (c.abstainable) _clear(c.ordinal),
    ];
    // A bug planted on the COME FROM fires at its entry, ahead of its faults (decision T23).
    final jump = c.faults.isEmpty || c.bug
        ? _jump(entry(comeFrom))
        : 'ickFatal(${c.faults.first.code}, ${c.next});';
    _line(guard.isEmpty ? jump : 'if (${guard.join(' && ')}) { $jump }');
  }

  void _body(IrStatement s) {
    final next = s.next;
    switch (s.op) {
      case IrAssign(:final target, :final value):
        _assign(target, value, next);
      case IrDimension(:final array, :final dimensions):
        _line(
          'ickDimension${array.wide ? '64' : ''}(${array.index}, [${dimensions.map((d) => _expr(d, next)).join(', ')}], $next);',
        );
      case IrNext(:final target):
        if (_natives[target] case final call?) _native(s, call);
        if (_library[target] case final native?) {
          _line('if (${_libraryGuard(native, _clear)}) {');
          _line('  ${_libraryCall(native)}');
          _line('  ${_jump(after(s.ordinal))}');
          _line('}');
        }
        _line('ickNextPush(${after(s.ordinal)}, $target);');
        _line(_jump(entry(target)));
      case final IrPetition petition:
        _line(_petition(petition, next));
      case IrForget(:final count):
        _line('ickForget(${_count(count, next)});');
      case IrResume(:final count):
        // An executed RESUME still springs a COME FROM aimed at it; only an executed NEXT waits
        // for its RESUME (§4.4.14.2).
        _line('final r = ickResume(${_count(count, next)}, $next);');
        _trap(s);
        _line('pc = r;');
        _line('break;');
      case IrGiveUp():
        _line('ickGiveUp();');
      case IrVarList(op: ListOp.stash, :final scalars, :final arrays):
        for (final v in scalars) {
          _line('ickStashScalar${_suffix(v)}(${v.index}, $next);');
          if (program.overloading) _line('ickOvStash(${_key(v)});');
        }
        for (final a in arrays) {
          _line('ickStashArray${_suffix(a)}(${a.index}, $next);');
        }
      case IrVarList(:final op, :final scalars, :final arrays)
          when op == ListOp.ignore || op == ListOp.remember:
        final ignored = op == ListOp.ignore;
        for (final v in scalars) {
          _line('${v.wide ? 'igw' : 'ig'}[${v.index}] = ${ignored ? 1 : 0};');
        }
        for (final a in arrays) {
          _line('ickArraySetIgnored${_suffix(a)}(${a.index}, $ignored);');
        }
      case IrVarList(op: ListOp.retrieve, :final scalars, :final arrays):
        for (final v in scalars) {
          _line('ickRetrieveScalar${_suffix(v)}(${v.index}, $next);');
          if (program.overloading) _line('ickOvRetrieve(${_key(v)});');
        }
        for (final a in arrays) {
          _line('ickRetrieveArray${_suffix(a)}(${a.index}, $next);');
        }
      case IrAbstain(:final abstain, :final targets, :final gerunds):
        final value = abstain ? 1 : 0;
        if (gerunds.isNotEmpty) {
          for (final g in gerunds) {
            _line('ger[${g.index}] = $value;');
            _line('gerT[${g.index}] = ++_clock;');
          }
        } else {
          for (final t in targets) {
            _line('ab[$t] = $value;');
            _line('abT[$t] = ++_clock;');
          }
        }
      case IrWriteIn(:final items, :final signed):
        for (final item in items) {
          _writeIn(item, next, signed: signed);
        }
      case IrReadOut(:final items, :final signed):
        for (final item in items) {
          if (item is IrArrayItem) {
            _line(
              'ickTuringOut${_suffix(item.array)}(${item.array.index}, $next);',
            );
          } else if (signed) {
            _line('ickReadOutSigned(${_expr(item, next)}, ${item.width});');
          } else {
            _line(
              'ickReadOut${item.width == 64 ? '64' : ''}(${_expr(item, next)});',
            );
          }
        }
      case IrComeFrom():
        break;
      case IrUndecodable(:final text):
        _line('ickUndecodable(${_string(text)}, $next);');
      case final op:
        throw ToolchainException('${op.runtimeType} is not implemented yet');
    }
  }

  /// A host service (R10, L29), given its variables' keys (64-bit scalars after the others) and
  /// array numbers.
  String _petition(IrPetition p, Object next) =>
      'ickPetition(${p.service}, [${p.scalars.map(_key).join(', ')}], '
      '[${p.arrays.map((a) => a.index).join(', ')}], $next);';

  /// When a native library routine can stand in for its INTERCAL: [clear] tests that a statement
  /// isn't abstained.
  String _libraryGuard(NativeLibraryCall c, String Function(int) clear) => [
    'ickNextFree() >= ${c.depth}',
    for (final w in c.watched) '${w.wide ? '_igw' : '_ig'}[${w.index}] == 0',
    for (final a in c.watchedArrays) '!ickArrayIgnored(${a.index})',
    for (final o in c.abstainable) clear(o),
  ].join(' && ');

  /// A native library routine: a PETITION alone, or the runtime's own version of a routine.
  String _libraryCall(NativeLibraryCall c) {
    if (c.petition case final petition?) {
      return _petition(petition, c.nexts.first.$2);
    }
    return 'ickLibrary(${c.label}, [${c.scalars.map(_key).join(', ')}], '
        '[${c.arrays.map((a) => a.index).join(', ')}], '
        '[${c.nexts.map((n) => '${n.$1}, ${n.$2}').join(', ')}]);';
  }

  /// Runs [call] in place of the NEXT [s] when the INTERCAL routine would behave the same, and
  /// falls through to the NEXT otherwise.
  void _native(IrStatement s, NativeCall call) {
    final guard = [
      'ickNextFree() >= ${call.depth}',
      for (final w in call.watched) 'ig[${w.index}] == 0',
      for (final o in call.abstainable) _clear(o),
    ];
    final args = [for (final a in call.args) 'v[${a.index}]'];
    if (args.length == 1) args.add('0');
    _line('if (${guard.join(' && ')}) {');
    _line('  final r = ickSyslib(${call.label}, ${args.join(', ')});');
    _line('  if (r >= 0) {');
    _line('    v[${call.result.index}] = r;');
    if (call.flag case final flag?) {
      _line('    v[${flag.index}] = r >> 32 == 0 ? 1 : 2;');
    }
    _line('    ${_jump(after(s.ordinal))}');
    _line('  }');
    _line('}');
  }

  /// Reads one number into [target]: element subscripts are checked first, then the number is
  /// read, then E275 (even when the target is IGNOREd, decision T24), then the store.
  void _writeIn(IrExpr target, Object next, {bool signed = false}) {
    switch (target) {
      case IrScalar() || IrElement():
        _line('{');
        _assign(
          target,
          signed
              ? IrInput(width: target.width, signed: true)
              : IrInput(width: target.width == 64 ? 64 : 32),
          next,
        );
        _line('}');
      case IrArrayItem(:final array):
        _line('ickTuringIn${_suffix(array)}(${array.index}, $next);');
      default:
        throw StateError('cannot WRITE IN $target');
    }
  }

  void _assign(IrExpr target, IrExpr value, Object next) {
    // A value can only exceed a narrower target; narrower ones were checked when they were stored.
    // 32 bits into 16 is Mode 1's E275, and anything wider is EXTRACAL's (R4).
    String checked(String v) {
      if (value.valueWidth <= target.width) return v;
      if (value is IrConst && value.value >= 0) {
        final max = target.width == 16 ? program.smallLimit : 0xFFFFFFFF;
        if (value.value <= max) return v;
      }
      return value.valueWidth == 32
          ? 'ickCheckSmall($v, $next)'
          : 'ickCheckNarrow($v, ${target.width}, $next)';
    }

    switch (target) {
      // An overloaded variable's assignment goes into its expression instead. WRITE IN stores
      // into the variable itself, as in `ick`.
      case IrScalar(:final slot) when program.overloading && value is! IrInput:
        final store = slot.wide ? 'w' : 'v', flags = slot.wide ? 'igw' : 'ig';
        _line('final u = ${_expr(value, next)};');
        _line('if (!ickOvSet(${_key(slot)}, u, $next)) {');
        _line(
          program.ignorable.contains(slot)
              ? '  final t = ${checked('u')};\n        if ($flags[${slot.index}] == 0) $store[${slot.index}] = t;'
              : '  $store[${slot.index}] = ${checked('u')};',
        );
        _line('}');
      case IrScalar(:final slot) when !program.ignorable.contains(slot):
        _line(
          '${slot.wide ? 'w' : 'v'}[${slot.index}] = ${checked(_expr(value, next))};',
        );
      case IrScalar(:final slot):
        final store = slot.wide ? 'w' : 'v', flags = slot.wide ? 'igw' : 'ig';
        _line('final t = ${checked(_expr(value, next))};');
        _line('if ($flags[${slot.index}] == 0) $store[${slot.index}] = t;');
      // A created operator in the value can re-dimension the array or go back to a choicepoint,
      // so the element is found again once the value is known.
      case IrElement(:final array, :final subscripts)
          when program.signatures.isNotEmpty:
        final suffix = _suffix(array);
        final values = _subscriptValues(subscripts, next);
        final names = [for (var i = 0; i < values.length; i++) 'k$i'];
        for (final (i, v) in values.indexed) {
          _line('final ${names[i]} = $v;');
        }
        _line('${_elementOf(array, names, next)};');
        _line('final t = ${checked(_expr(value, next))};');
        _line('final o = ${_elementOf(array, names, next)};');
        _line(
          program.ignorable.contains(array)
              ? 'if (!ickArrayIgnored$suffix(${array.index})) ickArrayData$suffix(${array.index})[o] = t;'
              : 'ickArrayData$suffix(${array.index})[o] = t;',
        );
      case IrElement(:final array, :final subscripts):
        final suffix = _suffix(array);
        _line('final o = ${_element(array, subscripts, next)};');
        _line('final t = ${checked(_expr(value, next))};');
        _line(
          program.ignorable.contains(array)
              ? 'if (!ickArrayIgnored$suffix(${array.index})) ickArrayData$suffix(${array.index})[o] = t;'
              : 'ickArrayData$suffix(${array.index})[o] = t;',
        );
      default:
        throw StateError('cannot assign to $target');
    }
  }

  /// `64` for EXTRACAL's 64-bit storage, whose runtime functions end in it.
  static String _suffix(Slot slot) => slot.wide ? '64' : '';

  /// A scalar's key in the runtime's overloading table: 64-bit scalars come after the others.
  int _key(Slot slot) =>
      slot.wide ? program.scalars.length + slot.index : slot.index;

  /// A scalar's true value, without its overloading.
  String _trueValue(Slot slot) => '${slot.wide ? 'w' : 'v'}[${slot.index}]';

  /// A FORGET or RESUME count.
  String _count(IrExpr count, Object next) => count.valueWidth == 64
      ? 'ickCount64(${_expr(count, next)})'
      : _expr(count, next);

  /// The checked offset of an element; one and two subscripts skip building a list.
  String _element(Slot array, List<IrExpr> subscripts, Object next) =>
      _elementOf(array, _subscriptValues(subscripts, next), next);

  List<String> _subscriptValues(List<IrExpr> subscripts, Object next) => [
    for (final s in subscripts)
      s.valueWidth == 64 ? 'ickSubscript64(${_expr(s, next)})' : _expr(s, next),
  ];

  String _elementOf(Slot array, List<String> values, Object next) {
    if (array.wide) {
      return 'ickElement64(${array.index}, [${values.join(', ')}], $next)';
    }
    return switch (values.length) {
      1 || 2 =>
        'ickElement${values.length}(${array.index}, ${values.join(', ')}, $next)',
      _ => 'ickElement(${array.index}, [${values.join(', ')}], $next)',
    };
  }

  /// A Dart int literal for a value's 64 bits.
  static String _literal(int value) => value >= 0
      ? '$value'
      : '0x${BigInt.from(value).toUnsigned(64).toRadixString(16).toUpperCase()}';

  String _expr(IrExpr e, Object next) => switch (e) {
    _ when e.width == IrExpr.runtimeWidth =>
      'ickXValue(${_wide(e, next)}, $next)',
    IrConst(:final value) => _literal(value),
    IrScalar(:final slot) when program.overloading =>
      'ickOvGet(${_key(slot)}, ${_trueValue(slot)}, ${slot.width}, $next)',
    IrScalar(:final slot) => _trueValue(slot),
    IrSlat(:final slot, :final id) =>
      'ickOvSlat(${_key(slot)}, $id, ${_trueValue(slot)})',
    // With created operators, the subscripts can change the array, so it is fetched after them.
    IrElement(:final array, :final subscripts)
        when program.signatures.isNotEmpty =>
      'ickArrayAt${_suffix(array)}(${array.index}, ${_element(array, subscripts, next)})',
    IrElement(:final array, :final subscripts) =>
      'ickArrayData${_suffix(array)}(${array.index})[${_element(array, subscripts, next)}]',
    IrMingle(:final left, :final right)
        when program.base == 2 && _fitsSmall(left) && _fitsSmall(right) =>
      'ickMingleSmall(${_expr(left, next)}, ${_expr(right, next)})',
    IrMingle(:final left, :final right) =>
      'ickMingle(${_expr(left, next)}, ${_expr(right, next)}, $next)',
    IrSelect(:final left, :final right)
        when left.width == IrExpr.runtimeWidth =>
      'ickXSelect(${_wide(left, next)}, ${_wide(right, next)}).\$3',
    IrSelect(:final left, right: IrConst(value: final mask))
        when program.base == 2 && e.width == 64 =>
      '${_selectFunction64(mask)}(${_expr(left, next)})',
    IrSelect(:final left, right: IrConst(value: final mask))
        when program.base == 2 && left.width != 64 =>
      '${_selectFunction(mask)}(${_expr(left, next)})',
    IrSelect(:final left, :final right)
        when left.width == 64 || right.width == 64 =>
      'ickSelect64(${_expr(left, next)}, ${_expr(right, next)})',
    IrSelect(:final left, :final right) =>
      'ickSelect(${_expr(left, next)}, ${_expr(right, next)})',
    IrUnary(:final op, :final operand) => _unary(op, operand, next),
    IrInput(signed: true, :final width) => 'ickWriteInSigned($width, $next)',
    IrInput(width: 64) => 'ickWriteIn64($next)',
    IrInput() => 'ickWriteIn($next)',
    IrArrayItem() => throw StateError('a whole array is not a value'),
    IrCreatedOp(signature: 0, :final left, :final right, :final text) =>
      'ickUnknownOperator(${_expr(left, next)}, ${_expr(right, next)}, ${_string(text)}, $next)',
    IrCreatedOp(
      :final signature,
      :final left,
      :final right,
      :final leftId,
      :final rightId,
      :final variables,
      :final text,
    ) =>
      'ickXOperator($signature, ${_expr(left, next)}, ${_expr(right, next)}, $leftId, $rightId, '
          '${variables.map((v) => v.index).join(', ')}, ${_string(text)}, $next)',
  };

  /// [e] as an [XValue] record of (width, high, low), for the operations whose result width
  /// depends on their operands' values: EXTRACAL's mingle and what is built on it (R5).
  String _wide(IrExpr e, Object next) => switch (e) {
    _ when e.width != IrExpr.runtimeWidth =>
      '(${e.width}, 0, ${_expr(e, next)})',
    IrMingle(:final left, :final right) =>
      'ickXMingle(${_wide(left, next)}, ${_wide(right, next)}, $next)',
    IrSelect(:final left, :final right) =>
      'ickXSelect(${_wide(left, next)}, ${_wide(right, next)})',
    IrUnary(:final op, :final operand) =>
      'ickXUnary(${UnaryOp.values.indexOf(op)}, ${_wide(operand, next)}, $next)',
    _ => throw StateError('$e has no run-time width'),
  };

  /// Whether [e] can't be above 65535: a small value, or a constant that fits.
  static bool _fitsSmall(IrExpr e) =>
      !e.large || (e is IrConst && e.value >= 0 && e.value <= 65535);

  /// A binary select by a constant mask becomes one shift and mask per run of 1-bits, or the
  /// compress steps when they're fewer, in a function per mask so the operand is evaluated once.
  final _selectFunctions = <int, String>{};

  String _selectFunction(int mask) =>
      _selectFunctions.putIfAbsent(mask, () => '_select$mask');

  /// A 64-bit select by a constant mask with few runs of 1-bits; [ickSelect64] does the rest.
  final _selectFunctions64 = <int, String>{};

  String _selectFunction64(int mask) {
    if (selectRuns(mask, bits: 64).length > 8) {
      return '((int x) => ickSelect64(x, ${_literal(mask)}))';
    }
    return _selectFunctions64.putIfAbsent(
      mask,
      () => '_select64x${BigInt.from(mask).toUnsigned(64).toRadixString(16)}',
    );
  }

  /// Binary uses rotate-and-combine bit operations; bases 3–7 use the digit-wise ones, where every
  /// logical operator is one that prefers a digit p (§6.6).
  String _unary(UnaryOp op, IrExpr operand, Object next) {
    final value = _expr(operand, next);
    final large = operand.large;
    if (program.base == 2) {
      final name = switch (op) {
        UnaryOp.and => 'And',
        UnaryOp.or => 'Or',
        UnaryOp.xor => 'Xor',
        _ => throw StateError('$op in binary is E997 at compile time'),
      };
      return 'ick$name${operand.width}($value)';
    }
    return switch (op) {
      UnaryOp.xor => 'ickMinus($large, $value)',
      UnaryOp.sharkfin => 'ickPlus($large, $value)',
      _ => 'ickLogical($large, ${preferredDigit(op, program.base)}, $value)',
    };
  }
}
