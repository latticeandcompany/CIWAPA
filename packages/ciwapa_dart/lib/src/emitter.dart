import 'package:ciwapa_core/ciwapa_core.dart';

/// Generates the Dart program for an [IrProgram].
///
/// Control flow is a `switch` on `pc` inside a loop. Statement N's entry is case 2N and its
/// "after" point, where any COME FROM trap fires and where a RESUME returns to a NEXT, is 2N + 1.
/// Case 1 is falling off the end of the program (E633).
class DartEmitter {
  DartEmitter(this.program, this.options);

  final IrProgram program;
  final EmitOptions options;
  final _out = StringBuffer();

  static int entry(int ordinal) => 2 * ordinal;
  static int after(int ordinal) => 2 * ordinal + 1;
  static const fellOff = 1;

  String emit() {
    if (program.base != 2) {
      throw ToolchainException('TriINTERCAL is not implemented yet');
    }
    final abstainable = program.statements.any((s) => s.abstainable);
    _out
      ..writeln(
        '// Generated by ciwapa-dart from ${options.sourceName}. Do not edit.',
      )
      ..writeln("import 'dart:typed_data';")
      ..writeln()
      ..writeln("import 'runtime.dart';")
      ..writeln()
      ..writeln('final v = Uint32List(${program.scalars.length});')
      ..writeln('final ig = Uint8List(${program.scalars.length});');
    if (abstainable) {
      _out.writeln('final ab = Uint8List(${program.statements.length + 1});');
    }
    _out
      ..writeln()
      ..writeln('void main(List<String> args) {')
      ..writeln(
        '  ickInit(args, base: ${program.base}, clockface: ${options.clockface}, '
        'arrayCount: ${program.arrays.length}, values: v, ignored: ig, messages: _messages);',
      );
    for (final s in program.statements) {
      if (s.initiallyAbstained) _out.writeln('  ab[${s.ordinal}] = 1;');
    }
    _out
      ..writeln('  _run();')
      ..writeln('}')
      ..writeln()
      ..writeln('void _run() {')
      ..writeln(
        '  var pc = ${program.statements.isEmpty ? fellOff : entry(1)};',
      )
      ..writeln('  while (true) {')
      ..writeln('    switch (pc) {')
      ..writeln('      case $fellOff:')
      ..writeln('        ickFatal(633, ${program.userStatements + 1});');
    for (final s in program.statements) {
      _statement(s);
    }
    _out
      ..writeln('      default:')
      ..writeln('        throw StateError("no statement at pc \$pc");')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln('}')
      ..writeln()
      ..writeln('const _messages = {');
    for (final m in IclError.all) {
      _out.writeln(
        '  ${m.code}: IckMessage(${_string(m.text)}, ${_string(m.joke)}),',
      );
    }
    _out.writeln('};');
    return _out.toString();
  }

  static String _string(String s) {
    final escaped = s
        .replaceAll(r'\', r'\\')
        .replaceAll("'", r"\'")
        .replaceAll(r'$', r'\$')
        .replaceAll('\n', r'\n')
        .replaceAll('\t', r'\t');
    return "'$escaped'";
  }

  void _line(String code) => _out.writeln('        $code');

  int _fallthrough(IrStatement s) {
    if (s.ordinal == program.userStatements ||
        s.ordinal == program.statements.length) {
      return fellOff;
    }
    return entry(s.ordinal + 1);
  }

  void _statement(IrStatement s) {
    final skip = 'pc = ${after(s.ordinal)}; break;';
    _out.writeln('      case ${entry(s.ordinal)}: // statement ${s.ordinal}');
    if (s.bug) _line('ickFatal(774, ${s.next});');
    if (s.op is! IrComeFrom) {
      final percent = s.percent;
      if (percent != null && percent < 100) {
        _line('if (!ickRoll($percent)) { $skip }');
      }
      if (s.abstainable) _line('if (ab[${s.ordinal}] != 0) { $skip }');
    }
    if (s.faults.isNotEmpty && s.op is! IrComeFrom) {
      _line('ickFatal(${s.faults.first.code}, ${s.next});');
    } else {
      _line('{');
      _body(s);
      _line('}');
    }
    _line('pc = ${after(s.ordinal)};');

    _out.writeln('      case ${after(s.ordinal)}:');
    _trap(s);
    _line('pc = ${_fallthrough(s)};');
  }

  /// The COME FROM trap after [s]: jumps to the COME FROM aimed at it when that COME FROM's own
  /// guard passes. A COME FROM's own faults fire in place of its jump (QUESTIONS.md L2).
  void _trap(IrStatement s) {
    final comeFrom = s.comeFrom;
    if (comeFrom == null) return;
    final c = program.at(comeFrom);
    final guard = [
      if (c.percent != null && c.percent! < 100) 'ickRoll(${c.percent})',
      if (c.abstainable) 'ab[${c.ordinal}] == 0',
    ];
    final jump = c.faults.isEmpty
        ? 'pc = ${entry(comeFrom)}; break;'
        : 'ickFatal(${c.faults.first.code}, ${c.next});';
    _line(guard.isEmpty ? jump : 'if (${guard.join(' && ')}) { $jump }');
  }

  void _body(IrStatement s) {
    final next = s.next;
    switch (s.op) {
      case IrAssign(:final target, :final value):
        _assign(target, value, next);
      case IrDimension(:final array, :final dimensions):
        _line(
          'ickDimension(${array.index}, [${dimensions.map((d) => _expr(d, next)).join(', ')}], $next);',
        );
      case IrNext(:final target):
        _line('ickNextPush(${after(s.ordinal)}, $target);');
        _line('pc = ${entry(target)};');
        _line('break;');
      case IrForget(:final count):
        _line('ickForget(${_expr(count, next)});');
      case IrResume(:final count):
        // An executed RESUME still springs a COME FROM aimed at it; only an executed NEXT waits
        // for its RESUME (§4.4.14.2).
        _line('final r = ickResume(${_expr(count, next)}, $next);');
        _trap(s);
        _line('pc = r;');
        _line('break;');
      case IrGiveUp():
        _line('ickGiveUp();');
      case IrVarList(op: ListOp.stash, :final scalars, :final arrays):
        for (final v in scalars) {
          _line('ickStashScalar(${v.index}, $next);');
        }
        for (final a in arrays) {
          _line('ickStashArray(${a.index}, $next);');
        }
      case IrVarList(:final op, :final scalars, :final arrays)
          when op == ListOp.ignore || op == ListOp.remember:
        final ignored = op == ListOp.ignore;
        for (final v in scalars) {
          _line('ig[${v.index}] = ${ignored ? 1 : 0};');
        }
        for (final a in arrays) {
          _line('ickArraySetIgnored(${a.index}, $ignored);');
        }
      case IrVarList(op: ListOp.retrieve, :final scalars, :final arrays):
        for (final v in scalars) {
          _line('ickRetrieveScalar(${v.index}, $next);');
        }
        for (final a in arrays) {
          _line('ickRetrieveArray(${a.index}, $next);');
        }
      case IrComeFrom():
        break;
      case IrUndecodable(:final text):
        _line('ickUndecodable(${_string(text)}, $next);');
      case final op:
        throw ToolchainException('${op.runtimeType} is not implemented yet');
    }
  }

  void _assign(IrExpr target, IrExpr value, int next) {
    String checked(String v) => target.large ? v : 'ickCheckSmall($v, $next)';
    switch (target) {
      case IrScalar(:final slot):
        _line('final t = ${checked(_expr(value, next))};');
        _line('if (ig[${slot.index}] == 0) v[${slot.index}] = t;');
      case IrElement(:final array, :final subscripts):
        _line(
          'final o = ickElement(${array.index}, [${subscripts.map((e) => _expr(e, next)).join(', ')}], $next);',
        );
        _line('final t = ${checked(_expr(value, next))};');
        _line(
          'if (!ickArrayIgnored(${array.index})) ickArrayData(${array.index})[o] = t;',
        );
      default:
        throw StateError('cannot assign to $target');
    }
  }

  String _expr(IrExpr e, int next) => switch (e) {
    IrConst(:final value) => '$value',
    IrScalar(:final slot) => 'v[${slot.index}]',
    IrElement(:final array, :final subscripts) =>
      'ickArrayData(${array.index})[ickElement(${array.index}, [${subscripts.map((s) => _expr(s, next)).join(', ')}], $next)]',
    IrMingle(:final left, :final right) =>
      'ickMingle(${_expr(left, next)}, ${_expr(right, next)}, $next)',
    IrSelect(:final left, :final right) =>
      'ickSelect(${_expr(left, next)}, ${_expr(right, next)})',
    IrUnary(:final op, :final operand) =>
      'ick${_unaryName(op)}${operand.large ? 32 : 16}(${_expr(operand, next)})',
    IrArrayItem() => throw ToolchainException(
      'Turing Text I/O is not implemented yet',
    ),
  };

  static String _unaryName(UnaryOp op) => switch (op) {
    UnaryOp.and => 'And',
    UnaryOp.or => 'Or',
    UnaryOp.xor => 'Xor',
    _ => throw ToolchainException(
      'TriINTERCAL operators are not implemented yet',
    ),
  };
}
