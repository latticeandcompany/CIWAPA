// Regenerates lib/src/runtime_c.g.dart from runtime.c. Run from the package:
//   dart run tool/embed_runtime.dart
import 'dart:io';

void main() =>
    File('lib/src/runtime_c.g.dart')
        .writeAsStringSync(embed(File('runtime.c').readAsStringSync()));

String embed(String runtime) {
  if (runtime.contains("'''")) throw StateError("runtime.c can't contain '''");
  return "// Generated by tool/embed_runtime.dart from runtime.c. Do not edit.\n"
      "const runtimeC = r'''\n$runtime''';\n";
}
