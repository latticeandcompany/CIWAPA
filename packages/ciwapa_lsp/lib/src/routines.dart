/// What one library routine takes and gives, from its row in a library's table.
class RoutineDoc {
  const RoutineDoc(this.label, this.library, this.fields);

  final int label;

  /// Which library or block it belongs to, such as `EXTRACAL library: I/O`.
  final String library;

  /// The row's cells by column, such as `Inputs` and `Results`, without the empty ones.
  final List<(String, String)> fields;

  String toMarkdown() {
    final lines = [
      '**($label)**, in the $library',
      '',
      for (final (column, value) in fields)
        '- **${switch (column) {
          'Inputs' => 'In',
          'Results' => 'Out',
          _ => column,
        }}:** $value',
    ];
    return lines.join('\n');
  }
}

/// The routines in [markdown]'s tables: every row whose first cell is a label such as `(1000)`.
/// Only tables with a `Results` column describe routines, and a label's first row wins. A
/// `## Name, (2000)–(2999)` heading names the block its tables belong to.
Map<int, RoutineDoc> parseRoutineTables(String markdown, String library) {
  final routines = <int, RoutineDoc>{};
  var block = library;
  List<String>? columns;
  for (final line in markdown.split('\n')) {
    if (line.startsWith('## ')) {
      final heading = line.substring(3);
      final comma = heading.indexOf(', (');
      block = comma < 0 ? library : '$library: ${heading.substring(0, comma)}';
      columns = null;
      continue;
    }
    if (!line.startsWith('|')) {
      columns = null;
      continue;
    }
    final cells = line
        .substring(1, line.lastIndexOf('|'))
        .split('|')
        .map((c) => c.trim())
        .toList();
    if (columns == null) {
      columns = cells;
      continue;
    }
    final label = RegExp(r'^\((\d+)\)$').firstMatch(cells.first);
    if (label == null || !columns.contains('Results')) continue;
    final number = int.parse(label.group(1)!);
    final header = columns;
    routines.putIfAbsent(
      number,
      () => RoutineDoc(number, block, [
        for (var i = 1; i < cells.length && i < header.length; i++)
          if (cells[i].isNotEmpty) (header[i], cells[i]),
      ]),
    );
  }
  return routines;
}

/// A Dart library holding the headings and tables of each README in [readmes] (by library name),
/// as `libraryTables`, for [parseRoutineTables] to read at run time. [generator] is the tool that
/// wrote it.
String generateLibraryTables(Map<String, String> readmes, String generator) {
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by $generator from the libraries\' READMEs. Do not edit.',
    )
    ..writeln()
    ..writeln('const libraryTables = <String, String>{');
  for (final MapEntry(key: library, value: text) in readmes.entries) {
    final kept = text
        .split('\n')
        .where((l) => l.startsWith('## ') || l.startsWith('|'))
        .join('\n');
    const quotes = "'''";
    out.writeln("  '$library': r$quotes\n$kept\n$quotes,");
  }
  out.writeln('};');
  return out.toString();
}
