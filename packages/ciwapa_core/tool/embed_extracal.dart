// Regenerates lib/src/extracal/library.g.dart from the blocks in lib/extracal. Run from the
// package:
//   dart run tool/embed_extracal.dart
import 'dart:io';

void main() =>
    File('lib/src/extracal/library.g.dart').writeAsStringSync(embed(sources()));

/// Each block's name and source, in name order.
Map<String, String> sources() {
  final files =
      Directory('lib/extracal')
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.xc'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  return {
    for (final f in files)
      f.uri.pathSegments.last.replaceAll('.xc', ''): f.readAsStringSync(),
  };
}

String embed(Map<String, String> sources) {
  final out = StringBuffer(
    '// Generated by tool/embed_extracal.dart from lib/extracal. Do not edit.\n'
    'const extracalSources = {\n',
  );
  for (final MapEntry(:key, :value) in sources.entries) {
    if (value.contains("'''")) throw StateError("$key.xc can't contain '''");
    out.write("  '$key': r'''\n$value''',\n");
  }
  out.write('};\n');
  return out.toString();
}
