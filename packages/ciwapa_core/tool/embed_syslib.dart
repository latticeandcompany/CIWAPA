// Regenerates lib/src/syslib/syslib.g.dart from lib/src/syslib/syslib.i. Run from the package:
//   dart run tool/embed_syslib.dart
import 'dart:io';

void main() => File(
  'lib/src/syslib/syslib.g.dart',
).writeAsStringSync(embed(File('lib/src/syslib/syslib.i').readAsStringSync()));

String embed(String syslib) {
  if (syslib.contains("'''")) throw StateError("syslib.i can't contain '''");
  return '// Generated by tool/embed_syslib.dart from lib/src/syslib/syslib.i. Do not edit.\n'
      "const syslibSource = r'''\n$syslib''';\n";
}
