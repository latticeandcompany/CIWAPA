import 'dart:io';

import 'package:ciwapa_core/ciwapa_core.dart';
import 'package:ciwapa_llvm/ciwapa_llvm.dart';
import 'package:test/test.dart';

void main() {
  late Directory temp;
  setUp(() => temp = Directory.systemTemp.createTempSync('flags-'));
  tearDown(() => temp.deleteSync(recursive: true));

  /// Builds a program that calls (1060) with --keep and returns the kept source.
  Future<String> kept(List<String> flags) async {
    final source = File('${temp.path}/prog.i')
      ..writeAsStringSync('DO .1 <- #1\nDO (1060) NEXT\nPLEASE GIVE UP\n');
    final exe = '${temp.path}/prog${Platform.isWindows ? '.exe' : ''}';
    final status = await runCli([
      'build',
      '--keep',
      '--no-random-bug',
      ...flags,
      source.path,
      '-o',
      exe,
    ], LlvmBackend());
    expect(status, 0);
    return File('${temp.path}/prog.ll').readAsStringSync();
  }

  test(
    '§10.2: --keep keeps the generated LLVM IR beside the executable',
    () async {
      expect(
        await kept([]),
        startsWith('; Generated by ciwapa-llvm from prog.i.'),
      );
    },
  );

  test('§10.2, Q37: --no-opt turns off the native library routines', () async {
    expect(await kept([]), contains('call i64 @ick_syslib(i32 1060, '));
    expect(await kept(['--no-opt']), isNot(contains('call i64 @ick_syslib(')));
  });
}
